"""Causal simulator of multi-stage container shipments.

Each shipment flows through:
    origin departure -> ocean transit -> port arrival -> berth -> discharge
    -> customs release -> truck pickup -> final delivery

Delays are generated by explicit mechanisms (not random noise added to the
final date), so they PROPAGATE realistically:
  * absorption  - early vessels wait for their berth window; early customs
                  release waits for the booked truck; carriers speed up to
                  recover lost time.
  * amplification - a vessel >24h late misses its berth window and joins the
                  back of the queue (worse under congestion); customs does not
                  process at weekends; a missed truck appointment must be
                  rebooked (worse in peak season).
  * shared shocks - congestion is a weekly time series per port, so a late
                  vessel can arrive into a *more* congested week.

Two files are produced:
  shipments_ground_truth.csv - every timestamp + true per-stage delay increments
  shipments.csv              - what an operator would see (some events missing)
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from .config import (CARGO, CARRIERS, CHOKEPOINTS, DEST_PORTS, ORIGIN_PORTS,
                     PEAK_MONTHS, PLAN, ROUTES, LATE_THRESHOLD_H)

H = pd.Timedelta(hours=1)
START = pd.Timestamp("2025-01-01")
N_WEEKS = 80


def _congestion_series(rng, base: float) -> np.ndarray:
    """Weekly AR(1) congestion index in [0.05, 0.98] with peak-season bumps."""
    c = np.empty(N_WEEKS)
    x = 0.0
    for w in range(N_WEEKS):
        month = (START + pd.Timedelta(weeks=w)).month
        bump = 0.15 if month in PEAK_MONTHS else 0.0
        x = 0.75 * x + rng.normal(0, 0.07)
        c[w] = np.clip(base + bump + x, 0.05, 0.98)
    return c


def _week(t: pd.Timestamp) -> int:
    return int(np.clip((t - START).days // 7, 0, N_WEEKS - 1))


def add_weekday_hours(t: pd.Timestamp, hours: float) -> pd.Timestamp:
    """Advance t by `hours` of working time; Saturday/Sunday do not count."""
    while hours > 1e-9:
        if t.weekday() >= 5:  # jump to Monday 00:00
            t = (t + pd.Timedelta(days=7 - t.weekday())).normalize()
            continue
        to_midnight = ((t.normalize() + pd.Timedelta(days=1)) - t) / H
        step = min(hours, to_midnight)
        t = t + step * H
        hours -= step
    return t


def _weather(rng, route: str, month: int) -> float:
    pacific = ROUTES[route]["dest"] in ("Los Angeles", "Long Beach", "New York")
    seasonal = 0.0
    if pacific and month in (7, 8, 9, 10):
        seasonal = 0.30  # typhoon season
    if not pacific and month in (11, 12, 1, 2):
        seasonal = 0.30  # North Atlantic / North Sea winter storms
    return float(np.clip(0.15 + seasonal + rng.beta(2, 5) * 0.6 - 0.1, 0, 1))


def simulate(n: int = 300, seed: int = 42) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    dest_cong = {p: _congestion_series(rng, v["congestion"]) for p, v in DEST_PORTS.items()}

    rows = []
    for i in range(n):
        route = rng.choice(list(ROUTES))
        r = ROUTES[route]
        port = DEST_PORTS[r["dest"]]
        carrier = rng.choice(list(CARRIERS), p=[0.3, 0.3, 0.25, 0.15])
        rel = CARRIERS[carrier]
        cargo = rng.choice(list(CARGO), p=[0.55, 0.25, 0.12, 0.08])
        docs_complete = rng.random() < 0.85
        containers = int(rng.integers(1, 41))

        sched_dep = START + pd.Timedelta(days=int(rng.integers(0, 365))) + int(rng.integers(6, 20)) * H
        month = sched_dep.month
        peak = month in PEAK_MONTHS
        origin_cong = float(np.clip(ORIGIN_PORTS[r["origin"]] + (0.12 if peak else 0) + rng.normal(0, 0.08), 0.05, 0.98))
        weather = _weather(rng, route, month)

        # ---------------- schedule (what the customer was promised) ----------
        T = r["transit_days"] * 24.0
        sched_arr = sched_dep + T * H
        sched_berth = sched_arr + PLAN["berth_wait"] * H
        sched_dis = sched_berth + PLAN["discharge"] * H
        sched_rel = sched_dis + port["customs_hours"] * 1.4 * H  # calendar allowance
        appointment = sched_rel + PLAN["appointment_buffer"] * H
        sched_del = appointment + r["inland_hours"] * H

        # forecasts available at booking time (noisy)
        cong_forecast = float(np.clip(dest_cong[r["dest"]][_week(sched_arr)] + rng.normal(0, 0.08), 0, 1))
        weather_forecast = float(np.clip(weather + rng.normal(0, 0.08), 0, 1))

        # ---------------- 1. origin departure --------------------------------
        p_roll = 0.03 + (0.08 if peak else 0) + 0.06 * (1 - rel)
        rolled = rng.random() < p_roll
        dep_delay = rng.gamma(1.2, 2 + 18 * (1 - rel) + 8 * origin_cong)
        if rolled:
            dep_delay += 168  # rolled to next weekly sailing
        act_dep = sched_dep + dep_delay * H

        # ---------------- 2. ocean transit -----------------------------------
        # schedules carry ~4% padding; bad weather eats into it
        transit = T * (0.96 + 0.05 * weather + rng.normal(0, 0.012))
        disrupted = False
        if r["chokepoint"]:
            cp = CHOKEPOINTS[r["chokepoint"]]
            if rng.random() < cp["p"]:
                disrupted = True
                transit += rng.uniform(*cp["hours"])
        recovery = min(0.25 * dep_delay, 72) * rel if dep_delay > 24 else 0.0  # speed up
        transit -= recovery
        act_arr = act_dep + transit * H
        arr_delay = (act_arr - sched_arr) / H

        # ---------------- 3. berth (congestion x lateness) -------------------
        c = float(dest_cong[r["dest"]][_week(act_arr)])
        base_wait = (3 + 50 * c ** 3) * rng.lognormal(0, 0.3)
        missed_window = arr_delay > 24
        if missed_window:  # lost berth slot -> back of the queue
            base_wait += (12 + 60 * c) * rng.uniform(0.6, 1.4)
            act_berth = act_arr + base_wait * H
        else:  # early / on-time vessels wait at anchor for their window
            act_berth = max(act_arr + base_wait * H, sched_berth - 6 * H)

        # ---------------- 4. discharge (yard congestion is nonlinear) --------
        dis_h = (PLAN["discharge"] * (1 + 2.5 * max(0.0, c - 0.6)) + 0.15 * containers) * rng.lognormal(0, 0.2)
        act_dis = act_berth + dis_h * H

        # ---------------- 5. customs (documents, inspection, weekends) -------
        p_insp = port["inspection_p"] * CARGO[cargo] * (1.6 if not docs_complete else 1.0)
        inspected = rng.random() < p_insp
        customs_work = port["customs_hours"] * rng.lognormal(-0.1, 0.35)
        if not docs_complete:
            customs_work += 24  # document query / amendment
        if inspected:
            customs_work += rng.uniform(48, 120)
        act_rel = add_weekday_hours(act_dis, customs_work)

        # ---------------- 6. inland (appointment absorbs / amplifies) --------
        if act_rel <= appointment:
            pickup = appointment  # early release absorbed by fixed truck slot
            rebooked = False
        else:
            pickup = act_rel + rng.uniform(4, 20) * (1 + (1.2 if peak else 0)) * H
            rebooked = True
        drive = r["inland_hours"] * (1 + 0.1 * weather) * rng.lognormal(0, 0.08)
        act_del = pickup + drive * H

        final_delay = (act_del - sched_del) / H

        # exact decomposition: increments telescope to final_delay
        inc = dict(
            inc_origin=dep_delay,
            inc_transit=transit - T,
            inc_berth=((act_berth - act_arr) - (sched_berth - sched_arr)) / H,
            inc_discharge=((act_dis - act_berth) - (sched_dis - sched_berth)) / H,
            inc_customs=((act_rel - act_dis) - (sched_rel - sched_dis)) / H,
            inc_inland=((act_del - act_rel) - (sched_del - sched_rel)) / H,
        )

        rows.append(dict(
            shipment_id=f"SHP{i:04d}", route=route, origin_port=r["origin"], dest_port=r["dest"],
            carrier=carrier, carrier_reliability=rel, cargo_type=cargo, docs_complete=int(docs_complete),
            containers=containers, peak_season=int(peak), chokepoint=r["chokepoint"] or "none",
            origin_congestion=round(origin_cong, 3), congestion_forecast=round(cong_forecast, 3),
            weather_forecast=round(weather_forecast, 3), congestion_at_arrival=round(c, 3),
            sched_departure=sched_dep, sched_port_arrival=sched_arr, sched_berth=sched_berth,
            sched_discharge=sched_dis, sched_customs_release=sched_rel, truck_appointment=appointment,
            sched_delivery=sched_del,
            act_departure=act_dep, act_port_arrival=act_arr, act_berth=act_berth,
            act_discharge=act_dis, act_customs_release=act_rel, act_delivery=act_del,
            customs_inspection=int(inspected),
            # hidden causes (ground truth only)
            rolled_over=int(rolled), chokepoint_disruption=int(disrupted), missed_berth_window=int(missed_window),
            truck_rebooked=int(rebooked), weather_true=round(weather, 3),
            **{k: round(v, 2) for k, v in inc.items()},
            final_delay_h=round(final_delay, 2), is_delayed=int(final_delay > LATE_THRESHOLD_H),
        ))
    df = pd.DataFrame(rows)
    ts = [c for c in df if c.startswith(("sched_", "act_")) or c == "truck_appointment"]
    df[ts] = df[ts].apply(lambda s: s.dt.round("min"))  # event feeds report to the minute
    return df


HIDDEN_COLS = ["rolled_over", "chokepoint_disruption", "missed_berth_window", "truck_rebooked",
               "weather_true", "inc_origin", "inc_transit", "inc_berth", "inc_discharge",
               "inc_customs", "inc_inland"]

MISSING_RATES = {  # share of events never reported by the data feed
    "act_port_arrival": 0.05, "act_berth": 0.15, "act_discharge": 0.15, "act_customs_release": 0.08,
}


def observed_view(gt: pd.DataFrame, seed: int = 7, scale: float = 1.0) -> pd.DataFrame:
    """Drop hidden columns and knock out intermediate events (EDI/AIS gaps)."""
    rng = np.random.default_rng(seed)
    obs = gt.drop(columns=HIDDEN_COLS).copy()
    for col, p in MISSING_RATES.items():
        mask = rng.random(len(obs)) < p * scale
        obs.loc[mask, col] = pd.NaT
    return obs
